export type IconId = (typeof ICONS)[number];

const ICON_SET: ReadonlySet<string> = new Set(ICONS);

export function isKnownIcon(value: string): value is IconId {
  return ICON_SET.has(value);
}

/** Up to `limit` known icons that contain the given text (case-insensitive), for error hints. */
export function suggestIcons(value: string, limit = 5): string[] {
  const needle = value.trim().toLowerCase();
  if (!needle) return [];
  return ICONS.filter(icon => icon.includes(needle)).slice(0, limit);
}
